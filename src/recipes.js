export function isPublished(recipe, now = new Date()) {
  return new Date(recipe.publishAt).getTime() <= now.getTime();
}

export function publishedRecipes(now = new Date()) {
  return RECIPES.filter(r => isPublished(r, now)).sort((a, b) => b.vol - a.vol);
}

function fmt(n) {
  return Number.isInteger(n) ? String(n) : n.toFixed(1);
}

// The LINE message text, in the same layout as the vol.1〜18 posts.
export function recipeMessageText(r) {
  const n = r.nutrition;
  return [
    `📱 【週刊：Body Make Recipe vol.${r.vol}】`,
    "",
    `「${r.title}」です！`,
    "",
    "🍴 材料（1人分）",
    ...r.ingredients,
    "",
    "🍳 作り方",
    r.steps.map((s, i) => `${i + 1}. ${s}`).join("\n\n"),
    "",
    "📊 栄養成分表示（1人分）",
    "",
    ` エネルギー： ${n.kcal} kcal`,
    ` P（タンパク質）： ${fmt(n.p)} g`,
    ` F（脂質）： ${fmt(n.f)} g`,
    ` C（炭水化物）： ${fmt(n.c)} g（糖質 ${fmt(n.sugar)}g / 食物繊維 ${fmt(n.fiber)}g）`,
    "",
    "💡 TTGYM's Point",
    r.point,
  ].join("\n");
}
